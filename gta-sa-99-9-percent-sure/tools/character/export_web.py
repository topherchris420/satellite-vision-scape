#!/usr/bin/env python3
"""Export CHRISW for the browser game (the hidden case on the Pine Gap site).

    python3 -I tools/character/export_web.py [--out ../src/game/hidden/chris/chrisw-mesh.json]

The mesh is the same procedural model build_chris.py makes, generated on the
repository's own synthetic skeleton (rw.sa_ped_skeleton(): hand-placed joint
positions, made-up bone orientations).  No game file is read, so nothing of
GTA San Andreas goes into the browser build.  The painted textures stay where
they are (assets/character/textures); the browser loads those PNGs directly.

Coordinates are the browser rig's: metres, +X the character's left, +Y up,
+Z forward, origin on the ground between the feet.  The model is scaled so
the Pelvis joint sits at the browser rig's pelvis height (0.98 m), which is
what seating and the animator assume.  Bones carry positions only (identity
orientation at bind), so the browser can pose them with the same rotations
the procedural characters use.  UVs keep the D3D convention (v = 0 at the top
of the image); load the textures with flipY = false.

The output is deterministic: the same sources give a byte-identical file.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
for p in (HERE, TOOLS):
    if p not in sys.path:
        sys.path.insert(0, p)

import numpy as np                                          # noqa: E402

import rw                                                   # noqa: E402
from rig import Rig                                         # noqa: E402
from chris_model import build_character                     # noqa: E402
from layout import MATERIALS, TEX_LENS                      # noqa: E402

MOD_ROOT = os.path.dirname(TOOLS)
REPO_ROOT = os.path.dirname(MOD_ROOT)
DEFAULT_OUT = os.path.join(REPO_ROOT, "src", "game", "hidden", "chris", "chrisw-mesh.json")
PELVIS_HEIGHT = 0.98          # src/game/player/CharacterVisual.ts


def b64(a, dtype):
    return base64.b64encode(np.ascontiguousarray(a, dtype=dtype).astype("<" + np.dtype(dtype).str[1:]).tobytes()).decode("ascii")


def to_browser(p):
    """Body-local (x right, y forward, z up) -> browser (x left, y up, z forward)."""
    p = np.asarray(p, float)
    return np.stack([-p[..., 0], p[..., 2], p[..., 1]], axis=-1)


def export():
    bones = rw.sa_ped_skeleton()
    rig = Rig.from_bonespecs(bones, source="synthetic (rw.sa_ped_skeleton)")
    ch = build_character(rig)
    m = ch.mesh

    V = to_browser(m["local_vertices"])
    N = to_browser(m["local_normals"])
    N /= np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-12)
    joints = to_browser(np.array([rig.local(b.name) for b in bones]))

    sole = float(V[:, 1].min())
    pelvis = joints[rig.index("Pelvis")]
    scale = PELVIS_HEIGHT / (float(pelvis[1]) - sole)
    centre = np.array([float(pelvis[0]), sole, float(pelvis[2])])
    V = (V - centre) * scale
    joints = (joints - centre) * scale

    # The local triangles are counter-clockwise seen from outside and the
    # mapping above is a rotation, so they stay front-facing; check anyway.
    T = np.asarray(m["triangles"], np.int64)
    a, b, c = V[T[:, 0]], V[T[:, 1]], V[T[:, 2]]
    facing = np.einsum("ij,ij->i", np.cross(b - a, c - a), N[T].mean(axis=1))
    if (facing < 0).sum() > (facing > 0).sum():
        T = T[:, [0, 2, 1]]
        facing = -facing
    outward = float((facing > 0).mean())

    # Draw groups in material order (the lenses last, as in the DFF).
    mats = np.asarray(m["material_ids"], np.int64)
    order = np.argsort(mats, kind="stable")
    T, mats = T[order], mats[order]
    groups = []
    for k in range(len(MATERIALS)):
        idx = np.nonzero(mats == k)[0]
        if len(idx):
            groups.append({"material": MATERIALS[k], "start": int(idx[0]) * 3, "count": int(len(idx)) * 3})

    BI = np.asarray(m["bone_indices"], np.int64)
    BW = np.asarray(m["bone_weights"], np.float64)
    BW = BW / BW.sum(axis=1, keepdims=True)
    UV = np.asarray(m["uvs"], np.float64)

    out = {
        "format": "chrisw-web-1",
        "about": ("Christopher Woodyard (CHRISW), generated by gta-sa-99-9-percent-sure/tools/character/"
                  "export_web.py on the repository's synthetic skeleton. Original work; no game files."),
        "units": "metres; +X the character's left, +Y up, +Z forward; origin between the feet",
        "uv": "v = 0 at the top of the texture (load textures with flipY = false)",
        "scale": round(scale, 6),
        "vertexCount": int(len(V)),
        "triangleCount": int(len(T)),
        "bones": [
            {"name": bn.name, "parent": int(bn.parent), "position": [round(float(x), 5) for x in joints[i]]}
            for i, bn in enumerate(bones)
        ],
        "materials": [{"name": n, "transparent": n == TEX_LENS} for n in MATERIALS],
        "groups": groups,
        "position": b64(V, np.float32),
        "normal": b64(N, np.float32),
        "uv0": b64(UV, np.float32),
        "index": b64(T, np.uint16),
        "skinIndex": b64(BI, np.uint8),
        "skinWeight": b64(BW, np.float32),
    }
    report = dict(vertices=len(V), triangles=len(T), outward_faces=outward, scale=scale,
                  height=float(V[:, 1].max()), groups=groups)
    return out, report


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=DEFAULT_OUT, help="output JSON (default src/game/hidden/chris/chrisw-mesh.json)")
    a = ap.parse_args(argv)
    out, report = export()
    text = json.dumps(out, indent=1, sort_keys=False) + "\n"
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("mesh     %d vertices, %d triangles, %.1f%% faces outward"
          % (report["vertices"], report["triangles"], 100 * report["outward_faces"]))
    print("size     %.3f m tall (scale %.4f)" % (report["height"], report["scale"]))
    print("wrote    %s (%d bytes, sha256 %s)" % (a.out, len(text), hashlib.sha256(text.encode()).hexdigest()[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
