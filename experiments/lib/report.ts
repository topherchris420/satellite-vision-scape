import type { NumberSummary, RateSummary } from "./aggregate";
import { EPISODE_GOALS, VARIABLES } from "./definition";
import { METRICS } from "./metrics";
import type { Evidence } from "./store";

/**
 * The human-readable report: Markdown, written next to the traces, easy to
 * commit and to diff. It is generated from `evidence()` alone, so every
 * number in it was re-measured from the trace files a moment ago. Sample
 * sizes are printed beside every number. Interpretation, the part a person
 * writes, belongs in the hypothesis backlog, not here.
 */

const isRate = (s: NumberSummary | RateSummary): s is RateSummary => "k" in s;
const pct = (x: number) => `${Math.round(x * 100)}%`;
const num = (x: number | null) =>
  x === null
    ? "—"
    : Number.isInteger(x)
      ? x.toLocaleString("en-GB")
      : x.toFixed(Math.abs(x) < 10 ? 2 : 1);

export function cell(s: NumberSummary | RateSummary | undefined, applicable = true): string {
  if (!applicable) return "n/a";
  if (!s || s.n === 0) return s && s.missing > 0 ? `— (${s.missing} not measured)` : "—";
  const miss = s.missing > 0 ? `, ${s.missing} not measured` : "";
  if (isRate(s)) return `${s.k}/${s.n} (${pct(s.wilson95![0])}–${pct(s.wilson95![1])})${miss}`;
  if (s.n === 1) return `${num(s.median)} (n = 1${miss})`;
  if (s.constant) return `${num(s.median)} (all ${s.n} runs${miss})`;
  return `${num(s.median)} [${num(s.min)}–${num(s.max)}] (n = ${s.n}${miss})`;
}

function evidenceLevel(ev: Evidence): string[] {
  const def = ev.result.definition;
  const ok = ev.measurements.filter((m) => m.status === "ok");
  const lines = [
    `- **Built:** definition \`${def.id}\` validates (${ev.result.provenance.definition.sha256.slice(0, 12)}).`,
  ];
  if (ok.length === 0) {
    lines.push("- **Ran:** no run with evidence yet.");
    return lines;
  }
  lines.push(
    `- **Ran:** ${ev.result.runs.length} runs recorded, ${ok.length} with a verified trace.`,
  );
  lines.push(`- **Observed:** the tables below, measured from those traces.`);
  const reproduced = ev.result.conditions.map((c) => {
    const n = ok.filter((m) => m.condition === c.id).length;
    if (!c.stochastic)
      return `\`${c.id}\` deterministic: ${n >= 2 ? `${n} runs, identical measurements ${allSame(ev, c.id) ? "yes" : "**no: investigate**"}` : "not repeated"}`;
    return `\`${c.id}\` ${n >= def.minRunsForVerdict ? `${n} seeded replicates` : `${n} runs (below the ${def.minRunsForVerdict} needed)`}`;
  });
  lines.push(`- **Reproduced:** ${reproduced.join("; ")}.`);
  lines.push(
    "- **Established:** never claimed by this tool. It would need the result to hold on another build, on other days and, for a model, on other model versions.",
  );
  return lines;
}

function allSame(ev: Evidence, condition: string): boolean {
  const runs = ev.measurements.filter((m) => m.condition === condition && m.status === "ok");
  return runs.every((r) => JSON.stringify(r.metrics) === JSON.stringify(runs[0].metrics));
}

export function renderReport(ev: Evidence): string {
  const { result } = ev;
  const def = result.definition;
  const p = result.provenance;
  const out: string[] = [];
  const conds = result.conditions;
  const human = (id: string) => conds.find((c) => c.id === id)?.config.provider === "human";

  out.push(`# ${def.title}`, "");
  out.push(
    `<sub>Experiment \`${def.id}\` · generated by \`bun run experiment report ${def.id}\` from the trace files below · ${result.status === "complete" ? "complete" : "**PARTIAL**"}</sub>`,
    "",
  );
  out.push("## Question", "", def.question, "");
  out.push("## Hypothesis", "", def.hypothesis, "");
  if (def.falsificationCriteria.length > 0)
    out.push(
      "**We would reconsider it if:**",
      "",
      ...def.falsificationCriteria.map((f) => `- ${f}`),
      "",
    );
  if (def.successCriteria.length > 0)
    out.push("**It is supported if:**", "", ...def.successCriteria.map((f) => `- ${f}`), "");
  out.push("## Why we asked", "", def.motivation.observation, "");
  if (def.motivation.evidence.length > 0)
    out.push(...def.motivation.evidence.map((e) => `- ${e}`), "");

  out.push("## Design", "");
  out.push(
    `- **Independent variable:** \`${def.independentVariable}\`: ${VARIABLES[def.independentVariable].describe}`,
  );
  const controlled = Object.entries(def.controlled);
  out.push(
    `- **Held fixed:** ${controlled.length ? controlled.map(([k, v]) => `\`${k}\` = \`${v}\``).join(", ") : "nothing beyond the world and task"}`,
  );
  out.push(
    `- **Episode:** from the start of After Hours until ${EPISODE_GOALS[def.episode.until]} (at most ${def.episode.maxSimSeconds} simulated s)`,
  );
  out.push(
    `- **Runs:** ${def.runsPerCondition} per condition; run *i* of every condition uses seed ${def.seed} + *i* (paired)`,
  );
  out.push(
    "",
    "| Condition | Setting | Provider | Runs | Repeats exactly? |",
    "| :-- | :-- | :-- | --: | :-- |",
  );
  for (const c of conds)
    out.push(
      `| \`${c.id}\` ${c.label} | \`${def.independentVariable}\` = \`${c.config[def.independentVariable]}\` | ${c.config.provider} | ${c.executedRuns} / ${c.plannedRuns}${c.skipped ? ` (${c.skipped})` : ""} | ${c.stochastic ? "no (seeded or live)" : "yes (deterministic)"} |`,
    );
  out.push("");

  out.push("## Result", "");
  out.push(
    "Median [min–max] (n) for measurements; k/n (Wilson 95%) for rates. † = agent only: not applicable to a person, never zero.",
    "",
  );
  out.push(`| Metric | ${conds.map((c) => `\`${c.id}\``).join(" | ")} |`);
  out.push(`| :-- | ${conds.map(() => "--:").join(" | ")} |`);
  for (const m of def.dependentMetrics) {
    const md = METRICS[m];
    const label = `${md.label}${md.scope === "agent_only" ? " †" : ""}`;
    out.push(
      `| ${label} | ${conds.map((c) => cell(ev.summaries[c.id]?.[m], !(md.scope === "agent_only" && human(c.id)))).join(" | ")} |`,
    );
  }
  out.push("");

  if (ev.predictions.length > 0) {
    out.push("## Predictions", "");
    out.push(
      "Judged by fixed rules ([docs/EXPERIMENTS.md](../../../docs/EXPERIMENTS.md#verdicts)), never by a model. A verdict covers this build and these conditions only.",
      "",
    );
    out.push(
      "| Prediction | Verdict | Pairs | Median change | Why |",
      "| :-- | :-- | --: | --: | :-- |",
    );
    for (const r of ev.predictions) {
      const pr = r.prediction;
      const what = `\`${pr.metric}\` ${pr.direction === "no_change" ? `unchanged (±${pr.minEffect})` : `${pr.direction}s by ≥ ${pr.minEffect}`} from \`${pr.from}\` to \`${pr.to}\``;
      out.push(
        `| ${what} | **${r.verdict}**${r.exact ? " (exact)" : ""} | ${r.pairs} | ${num(r.medianChange)} | ${r.reasons.join("; ")} |`,
      );
    }
    out.push("");
  }

  out.push("## What the traces show", "");
  let any = false;
  for (const c of conds) {
    const runs = ev.measurements.filter((m) => m.condition === c.id && m.status === "ok");
    if (runs.length === 0) continue;
    const records = result.runs.filter((r) => r.condition === c.id);
    const ends = new Map<string, number>();
    for (const r of records) ends.set(r.terminatedBy, (ends.get(r.terminatedBy) ?? 0) + 1);
    const kinds = new Map<string, number>();
    for (const r of runs)
      for (const f of ev.findings[r.runId] ?? [])
        if (f.severity !== "low") kinds.set(f.kind, (kinds.get(f.kind) ?? 0) + 1);
    const example = runs
      .map((r) => ({ r, f: (ev.findings[r.runId] ?? []).find((f) => f.severity !== "low") }))
      .find((x) => x.f);
    const endText = [...ends].map(([k, v]) => `${k} ×${v}`).join(", ");
    const findText = kinds.size
      ? [...kinds].map(([k, v]) => `${k} in ${v}`).join(", ")
      : "no high or medium findings";
    out.push(
      `- **\`${c.id}\`**: runs ended by ${endText}; diagnosis: ${findText}.${example ? ` Example, \`${example.r.runId}\`: ${example.f!.summary}.` : ""}`,
    );
    any = true;
  }
  if (!any) out.push("- No run with evidence yet.");
  if (ev.excluded.length > 0) {
    out.push("", "**Excluded from the aggregates** (listed, never averaged):", "");
    for (const e of ev.excluded) out.push(`- \`${e.runId}\`: ${e.reason}`);
  }
  out.push("");

  out.push("## Evidence level", "", ...evidenceLevel(ev), "");
  out.push("## Limitations", "");
  const limits = [...def.limitations];
  if (conds.some((c) => c.config.provider === "baseline"))
    limits.push(
      "The scripted baseline is a hand-written policy, not a model: its results describe what the world does to that policy, not what any model would do.",
    );
  limits.push(
    "Metrics are computed in the client from the session's own records; nothing here is server-attested.",
  );
  out.push(...limits.map((l) => `- ${l}`), "");

  out.push("## Provenance", "");
  out.push(
    `- **Commit:** \`${p.git.commit ?? "unknown"}\`${p.git.dirty ? " **with uncommitted code changes**" : ""} (${p.git.branch ?? "?"})`,
  );
  out.push(`- **Runtime:** Bun ${p.runtime.bun ?? "?"} · ${p.runtime.platform}/${p.runtime.arch}`);
  out.push(`- **Schemas:** ${Object.values(p.schemas).join(" · ")} · ${p.experimentSchema}`);
  out.push(
    `- **Definition:** \`${p.definition.path}\` (sha256 ${p.definition.sha256.slice(0, 16)})`,
  );
  if (p.latencySource && conds.some((c) => String(c.config.latency ?? "").startsWith("run-b")))
    out.push(
      `- **Latency source:** ${p.latencySource.samples} recorded latencies from \`${p.latencySource.file}\` (sha256 ${p.latencySource.sha256.slice(0, 16)})`,
    );
  const models = [...new Set(result.runs.map((r) => r.model).filter(Boolean))];
  if (models.length) out.push(`- **Models reported:** ${models.join(", ")}`);
  out.push(`- **Ran:** ${p.startedAt} → ${p.finishedAt ?? "(interrupted)"} · \`${p.command}\``, "");

  out.push("## Raw runs", "");
  out.push(
    "Every number above comes from these traces. Inspect one with `bun run trace <file>`; compare runs with `bun run compare <files…>`.",
    "",
  );
  const shown = def.dependentMetrics.slice(0, 4);
  out.push(
    `| Run | Seed | Status | Ended by | Sim s | ${shown.map((m) => `\`${m}\``).join(" | ")} | Trace |`,
  );
  out.push(`| :-- | --: | :-- | :-- | --: | ${shown.map(() => "--:").join(" | ")} | :-- |`);
  for (const r of result.runs) {
    const m = ev.measurements.find((x) => x.runId === r.runId)!;
    const link = r.trace ? `[${r.trace.file.replace("runs/", "")}](${r.trace.file})` : "none";
    out.push(
      `| \`${r.runId}\` | ${r.seed ?? "—"} | ${m.status} | ${r.terminatedBy} | ${r.simSeconds ?? "—"} | ${shown.map((k) => num(m.metrics[k] ?? null)).join(" | ")} | ${link} |`,
    );
  }
  out.push("");
  return out.join("\n");
}

/** The machine-readable twin of the report. */
export function summaryJson(ev: Evidence): unknown {
  return {
    schema: "svs-experiment-summary/v1",
    experiment: ev.result.experiment,
    status: ev.result.status,
    commit: ev.result.provenance.git.commit,
    conditions: ev.result.conditions.map((c) => ({
      id: c.id,
      config: c.config,
      runs: ev.measurements
        .filter((m) => m.condition === c.id)
        .map((m) => ({ runId: m.runId, status: m.status })),
      metrics: ev.summaries[c.id],
    })),
    predictions: ev.predictions,
    excluded: ev.excluded,
  };
}
